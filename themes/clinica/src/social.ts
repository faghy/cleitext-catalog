export const settingName = (network: Network) =>
  `social${network.key.charAt(0).toUpperCase()}${network.key.slice(1)}`;

/** Only https:// addresses become links (the url field also accepts /, mailto: and tel:). */
const HTTPS = /^https:\/\/\S+$/i;

export interface Profile {
  network: Network;
  url: string;
}

/** The profiles with a valid address, in the order of NETWORKS. */
export function profiles(settings: Record<string, unknown>): Profile[] {
  return NETWORKS.flatMap((network) => {
    const url = settings[settingName(network)];
    return typeof url === 'string' && HTTPS.test(url.trim()) ? [{ network, url: url.trim() }] : [];
  });
}
