"""Writes src/icons.ts: the brand icons of Font Awesome Free (CC BY 4.0, https://fontawesome.com/license/free)
used by the theme, read from the Font Awesome package of the Cleitext checkout, and the theme's own line icons."""
import json, pathlib, re
FA = next((pathlib.Path(__file__).parent / '../../../cleitext/node_modules/.pnpm').glob(
    '@fortawesome+fontawesome-free@*/node_modules/@fortawesome/fontawesome-free/svgs'))
BRANDS = {'facebook': 'facebook-f', 'twitter': 'twitter', 'x': 'x-twitter', 'instagram': 'instagram',
          'youtube': 'youtube', 'linkedin': 'linkedin-in', 'whatsapp': 'whatsapp', 'tiktok': 'tiktok',
          'telegram': 'telegram', 'spotify': 'spotify'}
out = {}
for key, name in BRANDS.items():
    svg = (FA / 'brands' / f'{name}.svg').read_text()
    out[key] = {'viewBox': re.search(r'viewBox="([^"]+)"', svg).group(1), 'd': re.search(r' d="([^"]+)"', svg).group(1)}
src = ('/** Generated by make-icons.py. Brand icons: Font Awesome Free 7, CC BY 4.0, https://fontawesome.com/license/free. */\n'
       f'export const BRANDS: Record<string, {{ viewBox: string; d: string }}> = {json.dumps(out, indent=1)};\n')
(pathlib.Path(__file__).parent / 'src' / 'icons.ts').write_text(src)
print(len(out), 'icons')
