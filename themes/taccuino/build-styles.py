"""Writes src/styles.ts from src/style.css (site), src/editor.css (block editor) and src/script.js (public script)."""
import json, pathlib, re
src = pathlib.Path(__file__).parent / 'src'


def mini(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    css = re.sub(r'\s+', ' ', css)
    return re.sub(r'\s*([{};,>])\s*', r'\1', css).replace(';}', '}').strip()


site = mini((src / 'style.css').read_text())
editor = mini((src / 'editor.css').read_text())
script = re.sub(r'^\s*/\*.*?\*/\s*', '', (src / 'script.js').read_text(), flags=re.S)
script = '\n'.join(l.strip() for l in script.splitlines() if l.strip())
(src / 'styles.ts').write_text(
    '// Generated by build-styles.py from style.css, editor.css and script.js.\n'
    f'export const css = {json.dumps(site)};\nexport const editorCss = {json.dumps(editor)};\n'
    f'export const script = {json.dumps(script)};\n')
print(len(site), len(editor), len(script))
